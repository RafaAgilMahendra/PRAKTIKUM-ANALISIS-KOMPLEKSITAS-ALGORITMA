"""Binary Search Iteratif

Best Case	O(1)
Average Case	O(log n)
Worst Case	O(log n)
"""

def binary_search(data, target):
    kiri = 0
    kanan = len(data) - 1

    while kiri <= kanan:
        tengah = (kiri + kanan) // 2

        if data[tengah] == target:
            return tengah
        elif data[tengah] < target:
            kiri = tengah + 1
        else:
            kanan = tengah - 1

    return -1

data = [10, 20, 30, 40, 50]

cari = 40
hasil = binary_search(data, cari)

if hasil != -1:
    print(hasil)
else:
    print("Data tidak ditemukan")

"""Binary Search Rekursif

Best Case	O(1)
Average Case	O(log n)
Worst Case	O(log n)
"""

def binary_search_rekursif(data, kiri, kanan, target):

    if kiri > kanan:
        return -1

    tengah = (kiri + kanan) // 2

    if data[tengah] == target:
        return tengah

    elif data[tengah] < target:
        return binary_search_rekursif(data, tengah + 1, kanan, target)

    else:
        return binary_search_rekursif(data, kiri, tengah - 1, target)


data = [10, 20, 30, 40, 50]

hasil = binary_search_rekursif(data, 0, len(data)-1, 20)

if hasil != -1:
    print(hasil)
else:
    print("Data tidak ditemukan")

"""Jump Search"""

import math

def jump_search(data, target):

    n = len(data)
    langkah = int(math.sqrt(n))
    awal = 0

    while awal < n and data[min(langkah, n) - 1] < target:
        awal = langkah
        langkah += int(math.sqrt(n))

        if awal >= n:
            return -1

    for i in range(awal, min(langkah, n)):
        if data[i] == target:
            return i

    return -1


data = [10, 20, 30, 40, 50, 60, 70]

hasil = jump_search(data, 60)

