def interpolation_search(data, target):

    low = 0
    high = len(data) - 1

    while low <= high and target >= data[low] and target <= data[high]:

        if low == high:
            if data[low] == target:
                return low
            return -1

        posisi = low + ((target - data[low]) * (high - low) //
                         (data[high] - data[low]))

        if data[posisi] == target:
            return posisi

        elif data[posisi] < target:
            low = posisi + 1

        else:
            high = posisi - 1

    return -1


data = [10, 20, 30, 40, 50]

hasil = interpolation_search(data, 50)

